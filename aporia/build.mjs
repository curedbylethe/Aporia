// ---------- Lacuna: Helix + Zed adapters ----------
// Paper and Ink are generated from the same semantic roles the web uses. No
// colour is introduced here; a host that cannot express a role gets the
// nearest role and the substitution is listed in lacuna/README.md.
// Hosts take opaque hex only, so a translucent rule is composited over its ground.
function solid(mode, key) {
  const raw = val(mode, key);
  const m = /rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)\s*(?:[\/,]\s*([\d.]+))?/.exec(raw);
  if (!m) return raw;
  const a = m[4] === undefined ? 1 : Number(m[4]);
  const ground = val(mode, 'bg.canvas');
  const g = [1, 3, 5].map((i) => parseInt(ground.slice(i, i + 2), 16));
  const mix = [1, 2, 3].map((i) => Math.round(Number(m[i]) * a + g[i - 1] * (1 - a)));
  return '#' + mix.map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase();
}

