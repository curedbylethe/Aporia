// ---------- flatten + resolve ----------
const flat = {};
(function walk(node, path) {
  if (node && typeof node === 'object' && '$value' in node) { flat[path.join('.')] = node; return; }
  for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...path, k]);
})(src, []);

const refOf = (v) => (typeof v === 'string' && /^\{(.+)\}$/.exec(v)?.[1]) || null;
const resolve = (path, seen = new Set()) => {
  assert(!seen.has(path), `alias cycle at ${path}`); seen.add(path);
  const t = flat[path]; assert(t, `unknown token ${path}`);
  const r = refOf(t.$value);
  return r ? resolve(r, seen) : t.$type === 'color' ? toHex(t.$value) : t.$value;
};
const prov = (path) => flat[path].$extensions?.aporia?.p ?? (refOf(flat[path].$value) ? 'alias' : 'n/a');

const modes = ['paper', 'ink'];
const semanticKeys = Object.keys(flat).filter((p) => p.startsWith('color.paper.')).map((p) => p.slice('color.paper.'.length));
for (const k of semanticKeys) assert(flat['color.ink.' + k], `ink is missing ${k}`); // dark/light equality
const val = (mode, key) => resolve(`color.${mode}.${key}`);

